/** 自主定义穿越时间：把玩家的描述解析成合法时间点 */
export function customTimePrompt(brief, points, line) {
  return `当前故事线：${line ? `${line.name}（${line.era}）` : '宿傩篇'}

玩家想自己指定穿越时机。他的话是：

> ${brief}

请把它解析成一个**合法**的时间点。

## 硬性约束

1. **anchorId 必须从下面这些既有时间点里选**，选最贴近玩家描述的那个。
   原作进度（哪些事件已经发生）与危险度都继承自它 —— 你不能发明新的进度状态。
2. **date 可以是自定义的**（YYYY-MM-DD，落在 2018-06-05 ~ 2019-12-31），
   这样玩家说"涩谷事变前一个月"时，日期能真的对上，而不是被硬塞到锚点上。
3. label / situation / hook 要贴着玩家的描述写，不要照抄锚点的原文 ——
   玩家要的是"我指定的那个时刻"，锚点只是用来定进度。

可选锚点：
${points.map((p) => `- ${p.id}　${p.label}（${p.date}）　已发生：${p.nodesDone.length ? p.nodesDone.join('、') : '无'}　危险度 ${p.danger}/5`).join('\n')}

若玩家说的时机在两可之间，优先选**进度更靠前**的那个（少替他决定已经发生的事）。`
}

