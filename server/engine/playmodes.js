export const DEFAULT_PLAY_MODE = 'story'

export const playModeOf = (id) => PLAY_MODES[id] || PLAY_MODES[DEFAULT_PLAY_MODE]

/** 给前端选模式用的精简信息 */
export function playModeBriefs() {
  return Object.values(PLAY_MODES).map(({ id, name, tagline, desc, accent }) => ({
    id, name, tagline, desc, accent,
  }))
}
