/**
 * 游玩模式。
 *
 * 和故事线是两个独立的轴：故事线决定"在哪条时间线上"，
 * 游玩模式决定"这条线怎么玩"。
 *
 * 它不改变任何数值规则（等级压制、伤害公式照旧），
 * 改的是**叙事配比**：剧情向允许剧情、关系、日常穿插；
 * 战斗向把它们压到最低，几乎每一轮都是战斗。
 */

