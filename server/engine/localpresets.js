export const PRESETS = RAW
export const presetOf = (id) => PRESETS.find((p) => p.id === id) || null
export const presetCount = () => PRESETS.length

/** 等级 → 该等级的预设数（给分布测试用） */
export function gradeDistribution() {
  const out = {}
  for (const p of PRESETS) out[p.grade] = (out[p.grade] || 0) + 1
  return out
}

/** 预设档案：数值走 sheet()，创意字段直接来自设计 —— 与 token 模式的
 *  rollAttributeProfile + decorateAttributeFlavor 输出同一形状，buildPlayer 直接可用 */
export function presetProfile(p) {
  const s = sheet(p.grade, p.lean, p.id)
  const tierName = DOMAIN_TIER[s.overall] || null
  return {
    slot: '预设',
    overallGrade: s.overall,
    ce: { ...s.ce, label: '咒力总量' },
    hp: { ...s.hp, label: '血条总量' },
    cursedDamage: { ...s.cursedDamage, label: '咒术伤害' },
    physicalDamage: { ...s.physicalDamage, label: '体术伤害' },
    efficiency: { ...s.efficiency, label: '咒力效率' },
    techniqueGrade: s.overall,
    techniqueMultiplier: TECH_MULT[s.overall],
    techniqueName: p.tech[0],
    techniqueEffect: p.tech[1],
    techniqueCooldown: p.tech[2],
    domainUnlocked: isTier(s.overall),
    domainTierName: tierName,
    reverseCursedTechnique: p.reverse,
    toolCount: p.tools.length,
    domain: isTier(s.overall)
      ? {
          unlocked: true,
          name: p.domain ? p.domain[0] : '未命名领域',
          sureHit: p.domain ? p.domain[1] : '',
          tierName,
          type: p.domain ? (normalizeDomainType(p.domain[2]) || defaultDomainTypeFor(tierName)) : defaultDomainTypeFor(tierName),
        }
      : { unlocked: false },
    talents: p.talents.slice(0, 3),
    playstyle: LEAN_TABLE[p.lean]?.style || '',
    tool: p.tools[0] || null,
  }
}

/** 预设身份：开局处境取自穿越时间点（和 token 模式一致），关系值只认本线名单 */
export function presetIdentity(p) {
  const point = byId(p.at, p.line) || firstPoint(p.line)
  const roster = new Set(charactersFor(p.line))
  const rel = {}
  for (const [k, v] of Object.entries(p.rel || {})) if (roster.has(k)) rel[k] = Math.max(-15, Math.min(15, v))
  return {
    slot: '预设',
    kind: p.kind,
    age: p.age,
    name: p.name,
    background: p.bg,
    mainlineRelation: p.mrel,
    openingSituation: point.situation,
    hook: p.hook,
    initialRelations: rel,
  }
}

/** 给前端选预设用的精简信息（不带正文，卡片只摆档案与卖点） */
export function presetBriefs() {
  return PRESETS.map((p) => {
    const line = storylineOf(p.line)
    const point = byId(p.at, p.line) || firstPoint(p.line)
    const prof = presetProfile(p)
    return {
      id: p.id,
      name: p.name,
      tag: p.tag,
      bg: p.bg,
      hook: p.hook,
      diff: p.diff,
      line: p.line,
      lineName: line.name,
      at: p.at,
      atLabel: point.label,
      grade: p.grade,
      style: LEAN_TABLE[p.lean]?.style || '',
      kind: p.kind,
      age: p.age,
      techName: p.tech[0],
      techEffect: p.tech[1],
      domainName: p.domain ? p.domain[0] : null,
      reverse: p.reverse,
      talents: p.talents,
      stats: {
        ce: prof.ce.value, hp: prof.hp.value,
        cd: prof.cursedDamage.value, pd: prof.physicalDamage.value,
        eff: `${Math.round(prof.efficiency.value * 100)}%`,
        mult: `×${prof.techniqueMultiplier}`,
      },
    }
  })
}
