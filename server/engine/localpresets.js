/** 预设的宽松写法 → 完整形状（效果字段缺省补 0 / 空对象） */
function P(raw) {
  return {
    ...raw,
    reverse: raw.reverse || '未掌握',
    tools: raw.tools || [],
    talents: raw.talents || [],
    domain: raw.domain || null,
    beats: raw.beats.map((b) => ({
      n: b.n,
      r: b.r || b.n.split(/[。！？\n]/)[0].slice(0, 60),
      d: (b.d || []).map(([s, t]) => ({ speaker: s, text: t })),
      c: b.c.map(([label, fx = {}]) => ({
        label,
        hp: fx.hp || 0,
        ce: fx.ce || 0,
        rel: fx.rel || {},
        time: fx.time || '0',
        flags: fx.flags || [],
        fg: fx.fg || null,
        k: fx.k ? { ...fx.k } : null,
      })),
    })),
  }
}

