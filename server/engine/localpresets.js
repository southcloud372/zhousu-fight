const POS = { lo: 0.25, mid: 0.5, hi: 0.75 }

/** 名字 → 0~1 的确定性散列（与 canon.js 同款）：同一预设每次开局的数值完全一致 */
function hash01(s) {
  let h = 2166136261 >>> 0
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i)
    h = Math.imul(h, 16777619) >>> 0
  }
  return h / 4294967296
}

/**
 * 按等级 + 倾向取一份属性。数值确定性生成（散列做 ±6% 的取点抖动），
 * 保证：① 落在该项等级的 RANGES 区间内；② 反推综合等级 === 声明等级。
 */
export function sheet(grade, lean, salt = '') {
  const plan = LEAN_TABLE[lean] || LEAN_TABLE.均衡
  const attr = (key, [shift, pos]) => {
    const gr = shiftGrade(grade, shift)
    const [lo, hi] = RANGES[gr][key]
    const t = Math.min(0.85, Math.max(0.15, POS[pos] + (hash01(`${salt}:${key}`) - 0.5) * 0.12))
    return { value: Math.round(lo + (hi - lo) * t), grade: gr }
  }
  const ce = attr('ce', plan.ce)
  const hp = attr('hp', plan.hp)
  const cd = attr('cd', plan.cd)
  const pd = attr('pd', plan.pd)
  const eff = { value: RANGES[grade].eff, grade }
  return {
    ce, hp, cursedDamage: cd, physicalDamage: pd, efficiency: eff,
    overall: overallFromGrades([ce.grade, hp.grade, cd.grade, pd.grade, eff.grade]),
  }
}

